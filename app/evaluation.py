from app.llm import chat_with_llm

def evaluate_answer(question: str, student_answer: str) -> str:
    user_message = f"""
    
    请根据下面的问题和答案，评估答案的质量。
    重要限制：
    1. 严禁编造实验数据、专家人数、用户人数、准确率、百分比、评分结果。
    2. 如果学生回答中没有提供实验数据，只能说“可以补充某类实验设计”，不能虚构实验结果。
    3. 参考回答必须基于学生已经提供的信息。
    4. 对于没有数据支撑的内容，要使用“可以从……角度设计评估”，不能写成“已经完成……实验”。
    不要虚构具体实验人数、样本数量、评分结果或百分比。
    如果需要提出实验设计，只能使用“若干名专家”“若干篇论文”“评分量表”等模糊表述。
    要求：
    1. 给回答打分，满分10
    2. 评估答案的优点是什么。
    3. 评估答案的不足之处是什么
    4. 给出改进建议。
    5. 给出一个更好的参考回答
    生成“更好的参考回答”时：
    1. 只能基于学生原始回答和问题本身进行改写。
    2. 不得声称“已经完成”“正在进行”“已联系”“已设计”等事实，除非学生回答中明确提供。
    3. 不得出现具体样本数量，例如 100 个问题、5 名专家、30 名学生。
    4. 如果学生回答是“不清楚”，参考回答只能表达“目前尚未明确，可以从……角度补充”，不能写成已有计划或已有进展。
    
    问题：{question}
    答案：{student_answer}
    """
    
    evaluation = chat_with_llm(user_message)
    return evaluation